// 어떤 수준을 얼마나 직접(d)/간접(i) 드러내는지 적어 둔다. 매핑을 바꾸려면 이 파일만 고치면 된다.
// V 의 '여유'는 소비가 또래보다 낮은 쪽, '과소비'는 높은 쪽이다.
// 이전 버전(6축 선호 문항 42개)은 archive/survey-v1-20261011/ 에 보관했다.

/** 금융 습관 지표의 수준을 가리키는 단서. d = 직접, i = 간접 */
export interface HabitEffect {
  metric: Metric;
  level: string;
  strength: 'd' | 'i';
}

/** 재무·부채 선호: 소득·재산·부채 축의 선호 수준 */
export interface AxisEffect {
  axis: AxisKey;
  level: number;
  w: number;
}

export type Effect = HabitEffect | AxisEffect;
export const isHabitEffect = (e: Effect): e is HabitEffect => 'metric' in e;

export interface QuestionOption {
  key: string;
  text: string;
  effects: Effect[];
  /** 중요도 문항(Q35): 이 선택지가 가장 중시한다고 가리키는 영역 */
  domain?: Domain;
  /** 중요도 문항(Q37): 영역 안에서 가장 중시하는 지표 */
  focus?: Metric;
  /** 저축 여력 없음·투자 안 함처럼 이 지표의 수준을 말하기 어렵다는 선택지 (점수에는 반영하지 않는다) */
  defer?: Metric;
}

/** importance = 무엇을 중시하는지, habit = 금융 습관 선호, finance = 재무 상태 선호, debt = 부채 상태 선호 */
export type Role = 'importance' | 'habit' | 'finance' | 'debt';

export interface Question {
  id: string;
  role: Role;
  part: string;
  title: string;
  text: string;
  options: QuestionOption[];
}

/** 어떤 문항에서든 고를 수 있는 "상관없음". 응답으로는 세지만 선호에는 영향을 주지 않는다. */
export const NO_PREFERENCE_KEY = 'N';

const h = (metric: Metric, level: string, strength: 'd' | 'i' = 'd'): HabitEffect => ({ metric, level, strength });
const ax = (axis: AxisKey, level: number, w = 1): AxisEffect => ({ axis, level, w });
type Opt = [text: string, effects?: Effect[], extra?: Pick<QuestionOption, 'domain' | 'focus' | 'defer'>];

function q(id: string, role: Role, part: string, title: string, text: string, opts: Opt[]): Question {
  const keys = ['A', 'B', 'C', 'D'];
  return {
    id,
    role,
    part,
    title,
    text,
    options: opts.map(([t, effects = [], extra = {}], i) => ({ key: keys[i], text: t, effects, ...extra })),
  };
}

